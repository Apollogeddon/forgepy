def normalise_workflow(content: str) -> str:
    """Line endings, trailing spaces and blank lines don't make a file the project's own."""
    lines = (line.rstrip() for line in content.replace("\r\n", "\n").split("\n"))
    return "\n".join(line for line in lines if line.strip())


def is_legacy_workflow(rel_path: str, content: str) -> bool:
    digest = hashlib.sha256(normalise_workflow(content).encode("utf-8")).hexdigest()
    return digest in LEGACY_WORKFLOWS.get(rel_path, frozenset())
